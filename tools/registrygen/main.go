// Command registrygen writes internal/catalog/apps_gen.go, which registers every
// App package under internal/apps. It reads the packages with go/parser and never
// imports the Catalog, so it runs when the registry is stale. It is a development
// tool and is not shipped with the binary.
package main

import (
	"bytes"
	"errors"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const (
	module     = "github.com/ajnart/self-host"
	appsDir    = "internal/apps"
	outputPath = "internal/catalog/apps_gen.go"
	// generatedPath registers its Apps through generatedApps(), so they stay out of
	// the registry until the file is removed.
	generatedPath = "internal/catalog/generated.go"
)

func main() {
	check := flag.Bool("check", false, "fail when the registry is stale instead of writing it")
	flag.Parse()
	if err := run(*check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(check bool) error {
	source, err := render()
	if err != nil {
		return err
	}
	if check {
		current, err := os.ReadFile(outputPath)
		if err != nil {
			return fmt.Errorf("read %s: %w", outputPath, err)
		}
		if !bytes.Equal(current, source) {
			return fmt.Errorf("%s is stale; run go run ./tools/registrygen", outputPath)
		}
		return nil
	}
	if err := os.WriteFile(outputPath, source, 0o644); err != nil {
		return err
	}
	fmt.Println(outputPath)
	return nil
}

type registration struct {
	pkg  string
	expr string
}

func render() ([]byte, error) {
	skip, err := importedApps(generatedPath)
	if err != nil {
		return nil, err
	}
	entries, err := os.ReadDir(appsDir)
	if err != nil {
		return nil, fmt.Errorf("read %s (run from the repository root): %w", appsDir, err)
	}
	var registrations []registration
	for _, entry := range entries {
		name := entry.Name()
		if !entry.IsDir() || name == "testdata" || strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_") || skip[name] {
			continue
		}
		exprs, err := appExprs(name)
		if err != nil {
			return nil, err
		}
		for _, expr := range exprs {
			registrations = append(registrations, registration{pkg: name, expr: expr})
		}
	}
	var out bytes.Buffer
	out.WriteString("// Code generated by tools/registrygen; DO NOT EDIT.\n\npackage catalog\n\nimport (\n\t\"" + module + "/internal/app\"\n")
	var imported []string
	for _, r := range registrations {
		if !slices.Contains(imported, r.pkg) {
			imported = append(imported, r.pkg)
			fmt.Fprintf(&out, "\t%q\n", module+"/"+appsDir+"/"+r.pkg)
		}
	}
	out.WriteString(")\n\nfunc registeredApps() []app.App {\n\treturn []app.App{\n")
	for _, r := range registrations {
		fmt.Fprintf(&out, "\t\t%s.%s,\n", r.pkg, r.expr)
	}
	out.WriteString("\t}\n}\n")
	return format.Source(out.Bytes())
}

// appExprs returns the expressions that build the Apps a package exposes. A
// package that declares exported constructors returning App (arr's Sonarr(),
// Radarr() and Prowlarr()) registers those; otherwise its App type is a ready
// value. A package with neither is a helper and registers nothing.
func appExprs(dir string) ([]string, error) {
	files, err := filepath.Glob(filepath.Join(appsDir, dir, "*.go"))
	if err != nil {
		return nil, err
	}
	var hasType bool
	var constructors []string
	for _, path := range files {
		if strings.HasSuffix(path, "_test.go") {
			continue
		}
		file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		if file.Name.Name != dir {
			return nil, fmt.Errorf("%s: package %s must be named after its directory %s", path, file.Name.Name, dir)
		}
		for _, decl := range file.Decls {
			switch decl := decl.(type) {
			case *ast.GenDecl:
				for _, spec := range decl.Specs {
					if ts, ok := spec.(*ast.TypeSpec); ok && ts.Name.Name == "App" {
						hasType = true
					}
				}
			case *ast.FuncDecl:
				if isConstructor(decl) {
					constructors = append(constructors, decl.Name.Name+"()")
				}
			}
		}
	}
	if len(constructors) > 0 {
		slices.Sort(constructors)
		return constructors, nil
	}
	if hasType {
		return []string{"App{}"}, nil
	}
	return nil, nil
}

func isConstructor(decl *ast.FuncDecl) bool {
	if decl.Recv != nil || !decl.Name.IsExported() || decl.Type.Params.NumFields() != 0 || decl.Type.Results.NumFields() != 1 {
		return false
	}
	switch result := decl.Type.Results.List[0].Type.(type) {
	case *ast.Ident:
		return result.Name == "App"
	case *ast.SelectorExpr:
		pkg, ok := result.X.(*ast.Ident)
		return ok && pkg.Name == "app" && result.Sel.Name == "App"
	}
	return false
}

func importedApps(path string) (map[string]bool, error) {
	imported := map[string]bool{}
	file, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.ImportsOnly)
	if errors.Is(err, os.ErrNotExist) {
		return imported, nil
	}
	if err != nil {
		return nil, err
	}
	for _, spec := range file.Imports {
		importPath, err := strconv.Unquote(spec.Path.Value)
		if err != nil {
			return nil, err
		}
		if dir, ok := strings.CutPrefix(importPath, module+"/"+appsDir+"/"); ok {
			imported[dir] = true
		}
	}
	return imported, nil
}
