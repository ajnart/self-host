const syntheticKey = "synthetic-stash-instance-key"

const validIdentity = `{"data":{"systemStatus":{"status":"OK"},"configuration":{"general":{"username":"admin"}},"version":{"version":"v0.32.0","hash":"synthetic-build-hash"}}}`

type fakeSecrets struct {
	values map[string]string
	writes int
}

func (s *fakeSecrets) Get(key string) string { return s.values[key] }
func (s *fakeSecrets) Set(key, value string) error {
	s.writes++
	s.values[key] = value
	return nil
}

type requests struct {
	anonymous, authenticated, unexpected int
}

type fakeStash struct {
	mu              sync.Mutex
	requests        requests
	anonymousStatus int
	status          int
	body            string
	redirect        string
}

func (f *fakeStash) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	f.mu.Lock()
	defer f.mu.Unlock()
	if r.Method == http.MethodGet && r.URL.Path == "/login" {
		w.WriteHeader(http.StatusOK)
		return
	}
	var query map[string]string
	if r.Method != http.MethodPost || r.URL.Path != "/graphql" || r.URL.RawQuery != "" || r.Header.Get("Cookie") != "" || json.NewDecoder(r.Body).Decode(&query) != nil || len(query) != 1 || query["query"] != `query { systemStatus { status } configuration { general { username } } version { version hash } }` {
		f.requests.unexpected++
		w.WriteHeader(http.StatusBadRequest)
		return
	}
	if r.Header.Get("ApiKey") == "" {
		f.requests.anonymous++
		w.WriteHeader(f.anonymousStatus)
		return
	}
	f.requests.authenticated++
	if r.Header.Get("ApiKey") != syntheticKey {
		w.WriteHeader(http.StatusUnauthorized)
		return
	}
	if f.redirect != "" {
		w.Header().Set("Location", f.redirect)
	}
	w.WriteHeader(f.status)
	w.Write([]byte(f.body))
}

func (f *fakeStash) observed() requests {
	f.mu.Lock()
	defer f.mu.Unlock()
	return f.requests
}

func newFixture(t *testing.T, f *fakeStash) (*helpers.H, *fakeSecrets, *[]helpers.StepResult) {
	t.Helper()
	server := httptest.NewServer(f)
	t.Cleanup(server.Close)
	deps := systemtest.NewDeps(t)
	secrets := &fakeSecrets{values: map[string]string{
		"ADMIN_USER": "admin", "ADMIN_PASSWORD": "synthetic-shared-password", "STASH_API_KEY": syntheticKey,
		"UNRELATED_KEY": "synthetic-unrelated-key",
	}}
	var recorded []helpers.StepResult
	h := helpers.New(helpers.Config{
		App: "stash", Service: "stash", BaseURL: server.URL, URL: server.URL,
		HTTP: server.Client(), Secrets: secrets, Log: events.Discard(),
		Now: deps.Now, Sleep: deps.Sleep,
		Record: func(result helpers.StepResult) { recorded = append(recorded, result) },
	})
	return h, secrets, &recorded
}

func TestOfficialDeploymentAndPrivatePersistence(t *testing.T) {
	a := stash.App{}
	info := a.Info()
	if info.ID != "stash" || info.Service != "stash" || info.Image != "stashapp/stash:latest" || info.Port != 9999 || info.ContainerPortFor(19999) != 9999 || !info.UsesMedia {
		t.Fatal("Stash's official image, identity or fixed container port changed")
	}
	compose := a.Compose(app.RenderContext{Port: 19999, Settings: map[string]string{"MEDIA_SEPARATE_USERS": "on"}})
	for _, required := range []string{
		"image: stashapp/stash:latest", "${BIND_IP}:19999:9999", "restart: unless-stopped", "STASH_CONFIG_FILE: /root/.stash/config.yml", `umask 077; exec stash \"$$@\"`,
		"./config:/root/.stash", "./metadata:/metadata", "./cache:/cache", "./blobs:/blobs", "./generated:/generated", "${MEDIA_ROOT}/adult:/data:ro",
	} {
		if !strings.Contains(compose, required) {
			t.Errorf("Compose is missing %q", required)
		}
	}
	for _, forbidden := range []string{"PUID", "PGID", "UMASK", "STASH_STASH", "STASH_API_KEY", "ADMIN_PASSWORD", "privileged:", "network_mode:", "container_name:", "docker.sock", "STASH_GENERATED", "STASH_METADATA"} {
		if strings.Contains(compose, forbidden) {
			t.Errorf("Compose contains unsupported identity, credential or selection setting %q", forbidden)
		}
	}
	if _, seedsFiles := any(a).(app.FileDeclarer); seedsFiles {
		t.Fatal("the App must not seed configuration or trigger ownership recovery for existing data")
	}
	if len(a.Links()) != 0 {
		t.Fatal("the App slice must not declare the later Homarr Link")
	}
	if _, generates := any(a).(app.SecretDeclarer); generates {
		t.Fatal("the Stash singleton key must never be generated by generic first-start secrets")
	}
	inputs := a.Inputs()
	if len(inputs) != 2 {
		t.Fatal("expected only existing-key and account recovery inputs")
	}
	for _, input := range inputs {
		if !input.Private || !input.RecoveryOnly || input.Required {
			t.Fatal("credential recovery must remain optional and private")
		}
	}
	if !strings.Contains(a.StandaloneGuide(), "does not bootstrap accounts or generate keys") {
		t.Fatal("standalone guidance must disclose partial automatic Setup")
	}
}

func TestExistingKeySetupCheckAndRerunAreReadOnly(t *testing.T) {
	f := &fakeStash{anonymousStatus: 401, status: 200, body: validIdentity}
	h, secrets, recorded := newFixture(t, f)
	before := map[string]string{}
	for key, value := range secrets.values {
		before[key] = value
	}
	for range 2 {
		if err := (stash.App{}).Setup(t.Context(), h); err != nil {
			t.Fatal(err)
		}
		if err := (stash.App{}).Check(t.Context(), h); err != nil {
			t.Fatal(err)
		}
	}
	observed := f.observed()
	if observed.unexpected != 0 || observed.anonymous != 4 || observed.authenticated != 4 || secrets.writes != 0 || !reflect.DeepEqual(before, secrets.values) {
		t.Fatal("Setup or Check changed credentials or made a request beyond read-only identity verification")
	}
	for _, result := range *recorded {
		if result.Status != stepstatus.StepSkip {
			t.Fatal("positively verified existing Setup should skip without mutation")
		}
	}
}

func TestSelectedExistingAccountIsNotRenamed(t *testing.T) {
	f := &fakeStash{anonymousStatus: 401, status: 200, body: strings.Replace(validIdentity, `"username":"admin"`, `"username":"synthetic-existing-owner"`, 1)}
	h, secrets, _ := newFixture(t, f)
	secrets.values["STASH_ACCOUNT_USERNAME"] = "synthetic-existing-owner"
	if err := (stash.App{}).Check(t.Context(), h); err != nil {
		t.Fatal(err)
	}
	if secrets.values["ADMIN_USER"] != "admin" || secrets.writes != 0 || f.observed().unexpected != 0 {
		t.Fatal("selecting an existing account changed the shared login or server")
	}
}

func TestUnsafeOrMissingPrerequisitesStayManual(t *testing.T) {
	for _, scenario := range []struct {
		name      string
		secrets   func(*fakeSecrets)
		anonymous int
		status    int
		body      string
		wantHint  string
		wantAuth  int
	}{
		{name: "missing key", secrets: func(s *fakeSecrets) { delete(s.values, "STASH_API_KEY") }, wantHint: "private stash.api_key"},
		{name: "missing account selection", secrets: func(s *fakeSecrets) { delete(s.values, "ADMIN_USER") }, wantHint: "private stash.account_username"},
		{name: "anonymous access", anonymous: 200, wantHint: "anonymous access"},
		{name: "anonymous redirect", anonymous: 302, wantHint: "anonymous access"},
		{name: "rejected key", status: 401, wantHint: "rejected the saved instance key", wantAuth: 2},
		{name: "forbidden key", status: 403, wantHint: "rejected the saved instance key", wantAuth: 2},
		{name: "different account", body: strings.Replace(validIdentity, `"username":"admin"`, `"username":"synthetic-other-owner"`, 1), wantHint: "does not match", wantAuth: 2},
		{name: "initial setup", body: strings.Replace(validIdentity, `"status":"OK"`, `"status":"SETUP"`, 1), wantHint: "Automatic bootstrap", wantAuth: 2},
		{name: "migration", body: strings.Replace(validIdentity, `"status":"OK"`, `"status":"NEEDS_MIGRATION"`, 1), wantHint: "explicit approval", wantAuth: 2},
	} {
		t.Run(scenario.name, func(t *testing.T) {
			f := &fakeStash{anonymousStatus: 401, status: 200, body: validIdentity}
			if scenario.anonymous != 0 {
				f.anonymousStatus = scenario.anonymous
			}
			if scenario.status != 0 {
				f.status = scenario.status
			}
			if scenario.body != "" {
				f.body = scenario.body
			}
			h, secrets, recorded := newFixture(t, f)
			if scenario.secrets != nil {
				scenario.secrets(secrets)
			}
			err := (stash.App{}).Setup(t.Context(), h)
			if !errors.Is(err, helpers.ErrManual) || errors.Is(err, helpers.ErrStepFailed) {
				t.Fatalf("expected an actionable Manual boundary, got %v", err)
			}
			last := (*recorded)[len(*recorded)-1]
			if last.Status != stepstatus.StepManual || !strings.Contains(last.Hint, scenario.wantHint) || last.Error != "" {
				t.Fatal("the specific recovery hint was not retained as Manual")
			}
			observed := f.observed()
			if observed.unexpected != 0 || observed.authenticated != scenario.wantAuth || secrets.writes != 0 {
				t.Fatal("Manual prerequisites triggered credential changes or unsafe requests")
			}
		})
	}
}

func TestIdentityRequiresCompleteSuccessfulGraphQLData(t *testing.T) {
	for _, body := range []string{
		`{}`, `{"data":null}`, `{"data":{}}`, `not JSON`,
		strings.Replace(validIdentity, `"data":`, `"errors":[{"message":"synthetic-private-response"}],"data":`, 1),
		strings.Replace(validIdentity, `"data":`, `"errors":[],"data":`, 1),
		strings.Replace(validIdentity, `"data":`, `"errors":null,"data":`, 1),
		strings.Replace(validIdentity, `"systemStatus":{"status":"OK"}`, `"systemStatus":null`, 1),
		strings.Replace(validIdentity, `"general":{"username":"admin"}`, `"general":null`, 1),
		strings.Replace(validIdentity, `"status":"OK"`, `"status":"UNKNOWN"`, 1),
		strings.Replace(validIdentity, `"version":"v0.32.0"`, `"version":null`, 1),
		strings.Replace(validIdentity, `"hash":"synthetic-build-hash"`, `"hash":""`, 1),
		strings.Replace(validIdentity, `"username":"admin"`, `"username":123`, 1),
	} {
		f := &fakeStash{anonymousStatus: 401, status: 200, body: body}
		h, secrets, _ := newFixture(t, f)
		err := (stash.App{}).Check(t.Context(), h)
		if err == nil || strings.Contains(err.Error(), "synthetic-private-response") || strings.Contains(err.Error(), syntheticKey) || secrets.writes != 0 {
			t.Fatal("incomplete GraphQL identity was accepted or its raw body escaped")
		}
	}
}

func TestInvalidKeyDoesNotReplaceExistingInstanceKey(t *testing.T) {
	f := &fakeStash{anonymousStatus: 401, status: 200, body: validIdentity}
	h, secrets, _ := newFixture(t, f)
	secrets.values["STASH_API_KEY"] = "synthetic-invalid-key"
	if err := (stash.App{}).Check(t.Context(), h); !errors.Is(err, helpers.ErrManual) {
		t.Fatal("a rejected key must require private recovery")
	}
	secrets.values["STASH_API_KEY"] = syntheticKey
	if err := (stash.App{}).Check(t.Context(), h); err != nil {
		t.Fatal(err)
	}
	if secrets.writes != 0 || f.observed().unexpected != 0 {
		t.Fatal("invalid-key recovery regenerated a credential or modified the server")
	}
}

func TestCredentialedRedirectIsNotFollowed(t *testing.T) {
	var mu sync.Mutex
	redirected := 0
	target := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, _ *http.Request) {
		mu.Lock()
		redirected++
		mu.Unlock()
		w.WriteHeader(200)
	}))
	t.Cleanup(target.Close)
	f := &fakeStash{anonymousStatus: 401, status: 302, redirect: target.URL}
	h, _, _ := newFixture(t, f)
	if err := (stash.App{}).Check(t.Context(), h); err == nil {
		t.Fatal("redirects cannot establish the selected identity")
	}
	mu.Lock()
	defer mu.Unlock()
	if redirected != 0 {
		t.Fatal("the instance key followed a redirect")
	}
}

type failingTransport struct{}

func (failingTransport) RoundTrip(*http.Request) (*http.Response, error) {
	return nil, fmt.Errorf("synthetic transport failure containing %s", syntheticKey)
}

func TestTransportDiagnosticsAreFixedAndCancellationSurvives(t *testing.T) {
	f := &fakeStash{anonymousStatus: 401, status: 200, body: validIdentity}
	h, _, _ := newFixture(t, f)
	h.Config.HTTP = &http.Client{Transport: failingTransport{}}
	if err := (stash.App{}).Check(t.Context(), h); err == nil || strings.Contains(err.Error(), syntheticKey) {
		t.Fatal("transport errors must not expose secret-bearing causes")
	}
	ctx, cancel := context.WithCancel(t.Context())
	cancel()
	if err := (stash.App{}).Check(ctx, h); !errors.Is(err, context.Canceled) {
		t.Fatal("identity requests must retain context cancellation")
	}
}
